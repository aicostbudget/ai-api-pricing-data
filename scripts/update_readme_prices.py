"""Regenerate the README price table from api/v1/prices.json.

The table sits between the two markers below and is rewritten by every release, so the
README always shows the prices the published API serves. `--check` fails when it is stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- price-table:start (generated by scripts/update_readme_prices.py; do not edit) -->"
END = "<!-- price-table:end -->"
# Model developers in README order; cloud resellers (aws, azure, google-cloud) are left to the full data.
PROVIDERS = (
    ("openai", "OpenAI"),
    ("anthropic", "Anthropic"),
    ("google-gemini", "Google Gemini"),
    ("xai", "xAI"),
    ("deepseek", "DeepSeek"),
    ("mistral-ai", "Mistral AI"),
    ("cohere", "Cohere"),
    ("moonshot-ai", "Moonshot AI (Kimi)"),
    ("alibaba-qwen", "Alibaba Qwen"),
    ("meta", "Meta"),
)
PAGE = "https://aicostbudget.com/en/providers/{slug}-api-pricing?utm_source=github&utm_medium=referral&utm_campaign=pricing_dataset&utm_content=readme_table_{content}"
MODEL_JSON = "https://aicostbudget.github.io/ai-api-pricing-data/api/v1/models/{provider}/{model}.json"


def usd(value: float | int | None) -> str:
    if value is None:
        return "–"
    return f"${value:,.4f}".rstrip("0").rstrip(".") if value < 0.01 else f"${value:,.2f}"


def token_priced(model: dict) -> bool:
    pricing = model["pricing"]
    return (
        model["status"] == "active" and pricing["unit"] == "1M tokens" and pricing["currency"] == "USD"
        and pricing["input"] is not None and pricing["output"] is not None
    )


def model_cell(model: dict) -> str:
    pricing = model["pricing"]
    url = MODEL_JSON.format(provider=model["provider_id"], model=model["model_id"])
    return f"[{model['display_name']}]({url}) {usd(pricing['input'])} / {usd(pricing['output'])}"


def render(dataset: dict) -> str:
    rows = [
        "| Provider | Active token-priced models | Lowest output price (input / output) | Highest output price (input / output) |",
        "| --- | ---: | --- | --- |",
    ]
    for provider_id, name in PROVIDERS:
        models = sorted(
            (model for model in dataset["models"] if model["provider_id"] == provider_id and token_priced(model)),
            key=lambda model: (model["pricing"]["output"], model["pricing"]["input"], model["model_id"]),
        )
        if not models:
            continue
        link = PAGE.format(slug=provider_id, content=provider_id.replace("-", "_"))
        highest = model_cell(models[-1]) if len(models) > 1 else "same model"
        rows.append(f"| [{name}]({link}) | {len(models)} | {model_cell(models[0])} | {highest} |")
    verified = dataset["last_verified_at"][:10]
    return "\n".join([
        START,
        f"USD per 1M tokens, standard list price. {dataset['model_count']} models tracked, last verified **{verified}**.",
        "",
        *rows,
        "",
        "Batch, cached-input, cache-write, long-context and non-token prices are in the full data.",
        END,
    ])


def updated_readme(readme: str, dataset: dict) -> str:
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise ValueError("README.md is missing the price-table markers")
    return readme[:start] + render(dataset) + readme[end + len(END):]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail if README.md is out of date")
    args = parser.parse_args()
    readme_path = args.root / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    dataset = json.loads((args.root / "api/v1/prices.json").read_text(encoding="utf-8"))
    expected = updated_readme(readme, dataset)
    if args.check:
        if expected != readme:
            sys.exit("README.md price table is stale; run python scripts/update_readme_prices.py")
        return
    if expected != readme:
        readme_path.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
