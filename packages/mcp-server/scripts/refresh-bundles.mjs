import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SITEMAP_URL = "https://aicostbudget.com/sitemap.xml";
const CACHE_TTL_MS = 24 * 60 * 60 * 1000;
const eventsInputUrl = new URL("../../../data/price-change-events/events.jsonl", import.meta.url);
const eventsOutputUrl = new URL("../src/generated/bundled-events.ts", import.meta.url);
const pagesOutputUrl = new URL("../src/generated/bundled-pages.ts", import.meta.url);
const pagesCacheUrl = new URL("../src/generated/model-pages-cache.json", import.meta.url);

const eventLines = (await readFile(eventsInputUrl, "utf8"))
  .split(/\r?\n/)
  .filter(Boolean);
const events = eventLines.map((line, index) => {
  try {
    return JSON.parse(line);
  } catch (error) {
    throw new Error(`Invalid price-change event at line ${index + 1}: ${error}`);
  }
});

await mkdir(dirname(fileURLToPath(eventsOutputUrl)), { recursive: true });
await writeFile(
  eventsOutputUrl,
  `// Generated by scripts/refresh-bundles.mjs. Do not edit by hand.\nexport const bundledPriceChangeEvents: unknown[] = ${JSON.stringify(events, null, 2)};\n`,
  "utf8",
);

let pageCache;
try {
  pageCache = JSON.parse(await readFile(pagesCacheUrl, "utf8"));
} catch {
  pageCache = null;
}

const cacheIsFresh = pageCache &&
  typeof pageCache.fetchedAt === "string" &&
  Array.isArray(pageCache.urls) &&
  Date.now() - Date.parse(pageCache.fetchedAt) < CACHE_TTL_MS;

if (!cacheIsFresh) {
  try {
    const response = await fetch(SITEMAP_URL, { signal: AbortSignal.timeout(10_000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const xml = await response.text();
    const urls = [...xml.matchAll(/<loc>\s*(https:\/\/aicostbudget\.com\/en\/models\/[^<]+)\s*<\/loc>/g)]
      .map((match) => match[1].trim())
      .sort();
    if (urls.length === 0) throw new Error("No English model pages found in sitemap");
    pageCache = { fetchedAt: new Date().toISOString(), urls };
    await writeFile(pagesCacheUrl, `${JSON.stringify(pageCache, null, 2)}\n`, "utf8");
  } catch (error) {
    if (!pageCache || !Array.isArray(pageCache.urls) || pageCache.urls.length === 0) {
      throw new Error(`Cannot generate model-page fallback: ${error}`);
    }
    console.warn(`Keeping stale sitemap fallback: ${error}`);
  }
}

await writeFile(
  pagesOutputUrl,
  `// Generated by scripts/refresh-bundles.mjs. Do not edit by hand.\n` +
    `export const bundledModelPagesFetchedAt = ${JSON.stringify(pageCache.fetchedAt)};\n` +
    `export const bundledModelPageUrls: string[] = ${JSON.stringify(pageCache.urls, null, 2)};\n`,
  "utf8",
);

console.log(`Bundled ${events.length} price-change events and ${pageCache.urls.length} model page URLs.`);
